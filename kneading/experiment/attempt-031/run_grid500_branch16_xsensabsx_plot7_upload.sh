#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../../.." && pwd)"
cd "${REPO_ROOT}"

OUTPUT_TAG="${ATTEMPT031_OUTPUT_TAG:-grid500_branch16_xpartialabsx_plot7_shimizu_morioka_cpu}"
PNG_PATH="${SCRIPT_DIR}/${OUTPUT_TAG}_contours.png"
UPLOAD_JSON="${SCRIPT_DIR}/${OUTPUT_TAG}_upload.json"
UPLOAD_STDERR="${SCRIPT_DIR}/${OUTPUT_TAG}_upload.stderr"

export JULIA_NUM_THREADS="${JULIA_NUM_THREADS:-32}"
export ATTEMPT031_OUTPUT_TAG="${OUTPUT_TAG}"
export ATTEMPT031_SWEEP_TAG="${ATTEMPT031_SWEEP_TAG:-${OUTPUT_TAG}}"
export ATTEMPT031_RUN_COLUMNS="${ATTEMPT031_RUN_COLUMNS:-true}"
export ATTEMPT031_WRITE_MERGED_RESULTS="${ATTEMPT031_WRITE_MERGED_RESULTS:-true}"
export ATTEMPT031_WRITE_LEGEND="${ATTEMPT031_WRITE_LEGEND:-true}"
export ATTEMPT031_N_ALPHA="${ATTEMPT031_N_ALPHA:-500}"
export ATTEMPT031_N_LAMBDA="${ATTEMPT031_N_LAMBDA:-500}"
export ATTEMPT031_MAX_EVENT_ITERATES="${ATTEMPT031_MAX_EVENT_ITERATES:-16}"
export ATTEMPT031_PLOT_ITERATE_CAP="${ATTEMPT031_PLOT_ITERATE_CAP:-7}"
export ATTEMPT031_OVERLAY_ITERATE_START="${ATTEMPT031_OVERLAY_ITERATE_START:-2}"
export ATTEMPT031_OVERLAY_ITERATE_END="${ATTEMPT031_OVERLAY_ITERATE_END:-7}"
export ATTEMPT031_LINEWIDTH="${ATTEMPT031_LINEWIDTH:-0.35}"
export ATTEMPT031_FIG_WIDTH="${ATTEMPT031_FIG_WIDTH:-2000}"
export ATTEMPT031_FIG_HEIGHT="${ATTEMPT031_FIG_HEIGHT:-2000}"
export ATTEMPT031_PX_PER_UNIT="${ATTEMPT031_PX_PER_UNIT:-4.0}"

echo "Running attempt-031 forward-sensitivity sweep and contour plot."
echo "Output tag: ${OUTPUT_TAG}"
echo "Threads: ${JULIA_NUM_THREADS}"
echo "Grid: ${ATTEMPT031_N_ALPHA} x ${ATTEMPT031_N_LAMBDA}"
echo "Stored iterates: ${ATTEMPT031_MAX_EVENT_ITERATES}, overlay range: ${ATTEMPT031_OVERLAY_ITERATE_START}:${ATTEMPT031_OVERLAY_ITERATE_END}"
echo "Figure: ${ATTEMPT031_FIG_WIDTH}x${ATTEMPT031_FIG_HEIGHT}, px_per_unit=${ATTEMPT031_PX_PER_UNIT}, linewidth=${ATTEMPT031_LINEWIDTH}"

julia --project=. "${SCRIPT_DIR}/contours.jl"

tglfs upload --json "${PNG_PATH}" > "${UPLOAD_JSON}" 2> "${UPLOAD_STDERR}"

echo "Uploaded ${PNG_PATH}"
