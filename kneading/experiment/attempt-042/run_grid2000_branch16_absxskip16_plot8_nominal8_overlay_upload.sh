#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../../.." && pwd)"
cd "${REPO_ROOT}"

SOURCE_COLUMNS_DIR="${ATTEMPT025_SWEEP_DIR:-${REPO_ROOT}/kneading/experiment/attempt-027/grid2000_branch16_absxskip16_plot8_deltatfix_nominal_iterates2_8_black_red_retired_shimizu_morioka_cpu_columns}"
OUTPUT_TAG="${ATTEMPT025_OUTPUT_TAG:-grid2000_branch16_absxskip16_plot8_deltatfix_nominal_iterate8_black_red_priorskips_freezeafterfirstplot_shimizu_morioka_cpu}"
PNG_PATH="${SCRIPT_DIR}/${OUTPUT_TAG}_contours.png"
UPLOAD_JSON="${SCRIPT_DIR}/${OUTPUT_TAG}_upload.json"
UPLOAD_STDERR="${SCRIPT_DIR}/${OUTPUT_TAG}_upload.stderr"

export JULIA_NUM_THREADS="${JULIA_NUM_THREADS:-32}"
export ATTEMPT025_OUTPUT_TAG="${OUTPUT_TAG}"
export ATTEMPT025_SWEEP_DIR="${SOURCE_COLUMNS_DIR}"
export ATTEMPT025_RUN_COLUMNS="${ATTEMPT025_RUN_COLUMNS:-false}"
export ATTEMPT025_WRITE_MERGED_RESULTS="${ATTEMPT025_WRITE_MERGED_RESULTS:-false}"
export ATTEMPT025_WRITE_ITERATE_STATS="${ATTEMPT025_WRITE_ITERATE_STATS:-true}"
export ATTEMPT025_N_ALPHA="${ATTEMPT025_N_ALPHA:-2000}"
export ATTEMPT025_N_LAMBDA="${ATTEMPT025_N_LAMBDA:-2000}"
export ATTEMPT025_MAX_EVENT_ITERATES="${ATTEMPT025_MAX_EVENT_ITERATES:-16}"
export ATTEMPT025_PLOT_ITERATE_CAP="${ATTEMPT025_PLOT_ITERATE_CAP:-8}"
export ATTEMPT025_LINEWIDTH="${ATTEMPT025_LINEWIDTH:-0.35}"
export ATTEMPT025_FIG_WIDTH="${ATTEMPT025_FIG_WIDTH:-2000}"
export ATTEMPT025_FIG_HEIGHT="${ATTEMPT025_FIG_HEIGHT:-2000}"
export ATTEMPT025_PX_PER_UNIT="${ATTEMPT025_PX_PER_UNIT:-4.0}"
export ATTEMPT027_OVERLAY_ITERATE_START="${ATTEMPT027_OVERLAY_ITERATE_START:-8}"
export ATTEMPT027_OVERLAY_ITERATE_END="${ATTEMPT027_OVERLAY_ITERATE_END:-8}"
export ATTEMPT027_RETIRE_ON_SKIP="${ATTEMPT027_RETIRE_ON_SKIP:-false}"
export ATTEMPT027_FREEZE_AFTER_ANY_PLOT="${ATTEMPT027_FREEZE_AFTER_ANY_PLOT:-true}"
export ATTEMPT027_COLOR_RETURNTIME_MAXIMA="${ATTEMPT027_COLOR_RETURNTIME_MAXIMA:-false}"
export ATTEMPT027_FLOOD_COMPONENT_COLORS="${ATTEMPT027_FLOOD_COMPONENT_COLORS:-false}"
export ATTEMPT042_COLOR_VISIBLE_CONTOURS_RED_AFTER_PRIOR_SKIP="${ATTEMPT042_COLOR_VISIBLE_CONTOURS_RED_AFTER_PRIOR_SKIP:-true}"

echo "Running attempt-042 nominal-iterate-8-only overlay from saved attempt-027 sweep."
echo "Output tag: ${OUTPUT_TAG}"
echo "Source columns: ${SOURCE_COLUMNS_DIR}"
echo "Threads: ${JULIA_NUM_THREADS}"
echo "Grid: ${ATTEMPT025_N_ALPHA} x ${ATTEMPT025_N_LAMBDA}"
echo "Stored iterates: ${ATTEMPT025_MAX_EVENT_ITERATES}, plotted nominal iterates: 1:${ATTEMPT025_PLOT_ITERATE_CAP}, overlay range: ${ATTEMPT027_OVERLAY_ITERATE_START}:${ATTEMPT027_OVERLAY_ITERATE_END}"
echo "Figure: ${ATTEMPT025_FIG_WIDTH}x${ATTEMPT025_FIG_HEIGHT}, px_per_unit=${ATTEMPT025_PX_PER_UNIT}, linewidth=${ATTEMPT025_LINEWIDTH}"

julia --project=. "${SCRIPT_DIR}/contours.jl"

tglfs upload --json "${PNG_PATH}" > "${UPLOAD_JSON}" 2> "${UPLOAD_STDERR}"

echo "Uploaded ${PNG_PATH}"
